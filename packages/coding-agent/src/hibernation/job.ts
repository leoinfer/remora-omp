/**
 * Independent job execution for hibernation.
 *
 * An experiment is a transient systemd *user* unit. That is what makes it
 * outlive OMP: the unit lives in the user manager's cgroup (linger is enabled
 * on this host), not in the agent process. OMP may exit or crash; the unit
 * keeps running until it finishes, is stopped, or the machine reboots.
 *
 * The runner writes a result contract (`result.json`) atomically. The external
 * watcher consumes that contract; it never needs OMP's in-memory job manager.
 */

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { createHash } from "node:crypto";
import { logger, toError } from "@oh-my-pi/pi-utils";
import {
	type ArtifactDigest,
	type HibernationJob,
	type HibernationRecord,
	type JobResult,
	parseJobResult,
} from "./types";
import { type HibernationPaths, hibernationPaths } from "./store";

const SYSTEMCTL_TIMEOUT_MS = 15_000;
const RESULT_VERSION = 1;

export interface CommandResult {
	exitCode: number;
	stdout: string;
	stderr: string;
}

/** Run a short control command without a shell. */
export function runCommand(argv: string[], options: { timeoutMs?: number; cwd?: string } = {}): CommandResult {
	const proc = Bun.spawnSync(argv, {
		cwd: options.cwd,
		stdin: "ignore",
		stdout: "pipe",
		stderr: "pipe",
		timeout: options.timeoutMs ?? SYSTEMCTL_TIMEOUT_MS,
		env: process.env,
	});
	return {
		exitCode: proc.exitCode ?? 1,
		stdout: proc.stdout ? new TextDecoder().decode(proc.stdout) : "",
		stderr: proc.stderr ? new TextDecoder().decode(proc.stderr) : "",
	};
}

function sanitizeUnitPart(value: string): string {
	const cleaned = value
		.toLowerCase()
		.replace(/[^a-z0-9_.-]+/g, "-")
		.replace(/^-+|-+$/g, "")
		.slice(0, 40);
	return cleaned || "job";
}

export function newRunId(jobId: string): string {
	return `${sanitizeUnitPart(jobId)}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

export function unitNameFor(runId: string): string {
	return `omp-hiber-${sanitizeUnitPart(runId)}`;
}

export function sha256Text(text: string): string {
	return createHash("sha256").update(text).digest("hex");
}

export function sha256File(file: string): string {
	const hash = createHash("sha256");
	const fd = fs.openSync(file, "r");
	try {
		const buffer = Buffer.alloc(1024 * 1024);
		let read = 0;
		while ((read = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0) {
			hash.update(buffer.subarray(0, read));
		}
	} finally {
		fs.closeSync(fd);
	}
	return hash.digest("hex");
}

export function systemdUserAvailable(): { available: boolean; detail: string } {
	const result = runCommand(["systemctl", "--user", "show-environment"]);
	if (result.exitCode === 0) return { available: true, detail: "user manager reachable" };
	return {
		available: false,
		detail: (result.stderr || result.stdout).trim() || "systemctl --user is unavailable",
	};
}

export interface LaunchJobInput {
	jobId: string;
	command: string;
	cwd: string;
	timeoutMs: number;
	requiredArtifacts: string[];
	successExitCodes?: number[];
	/** Keep the job after OMP exits even if the user manager restarts at boot. */
	persistent?: boolean;
	paths?: HibernationPaths;
}

export interface LaunchedJob {
	job: HibernationJob;
	invocationId?: string;
}

const RUNNER_SCRIPT = String.raw`#!/usr/bin/env bash
# Generated by OMP hibernation. Do not edit; it is re-created per run.
set -u
umask 077
result_dir="$OMP_HIB_RESULT_DIR"
job_id="$OMP_HIB_JOB_ID"
run_id="$OMP_HIB_RUN_ID"
unit="$OMP_HIB_UNIT"
command_sha="$OMP_HIB_COMMAND_SHA"
command_text="$(cat "$result_dir/command.txt")"
job_cwd="$(cat "$result_dir/cwd.txt")"
cd "$job_cwd" 2>/dev/null || {
	printf '{"version":1,"runId":"%s","unit":"%s","commandSha256":"%s","startedAt":"","finishedAt":"","exitCode":125,"durationMs":0,"stdoutPath":"","stderrPath":"","artifacts":[]}\n' "$run_id" "$unit" "$command_sha" > "$result_dir/result.json"
	exit 125
}
started_at="$(date -u +%Y-%m-%dT%H:%M:%S.%3NZ)"
start_ms="$(date +%s%3N)"
/bin/bash -lc "$command_text" >"$result_dir/stdout.log" 2>"$result_dir/stderr.log"
code=$?
finished_at="$(date -u +%Y-%m-%dT%H:%M:%S.%3NZ)"
end_ms="$(date +%s%3N)"
export OMP_HIB_STARTED_AT="$started_at"
export OMP_HIB_FINISHED_AT="$finished_at"
export OMP_HIB_EXIT_CODE="$code"
export OMP_HIB_DURATION_MS="$((end_ms - start_ms))"
python3 - "$result_dir" <<'PY'
import hashlib, json, os, sys
result_dir = sys.argv[1]
run_id = os.environ["OMP_HIB_RUN_ID"]
unit = os.environ["OMP_HIB_UNIT"]
command_sha = os.environ["OMP_HIB_COMMAND_SHA"]
def digest(path):
    h = hashlib.sha256()
    size = 0
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            size += len(chunk)
            h.update(chunk)
    return size, h.hexdigest()
artifacts = []
list_path = os.path.join(result_dir, "artifacts.list")
if os.path.exists(list_path):
    with open(list_path, "r", encoding="utf-8") as handle:
        for line in handle:
            candidate = line.rstrip("\n")
            if not candidate or not os.path.isfile(candidate):
                continue
            size, sha = digest(candidate)
            artifacts.append({"path": candidate, "size": size, "sha256": sha})
payload = {
    "version": 1,
    "runId": run_id,
    "unit": unit,
    "commandSha256": command_sha,
    "startedAt": os.environ["OMP_HIB_STARTED_AT"],
    "finishedAt": os.environ["OMP_HIB_FINISHED_AT"],
    "exitCode": int(os.environ["OMP_HIB_EXIT_CODE"]),
    "durationMs": int(os.environ["OMP_HIB_DURATION_MS"]),
    "stdoutPath": os.path.join(result_dir, "stdout.log"),
    "stderrPath": os.path.join(result_dir, "stderr.log"),
    "artifacts": artifacts,
}
tmp = os.path.join(result_dir, "result.json.tmp")
with open(tmp, "w", encoding="utf-8") as handle:
    json.dump(payload, handle, indent=2, sort_keys=True)
    handle.flush()
    os.fsync(handle.fileno())
os.replace(tmp, os.path.join(result_dir, "result.json"))
PY
exit "$code"
`;

/** Create the runner script and result directory for one run. */
export function prepareJobDir(input: LaunchJobInput): {
	runId: string;
	unit: string;
	resultDir: string;
	runnerPath: string;
} {
	const paths = input.paths ?? hibernationPaths();
	const runId = newRunId(input.jobId);
	const unit = unitNameFor(runId);
	const resultDir = path.join(paths.jobs, runId);
	fs.mkdirSync(resultDir, { recursive: true, mode: 0o700 });
	const runnerPath = path.join(resultDir, "runner.sh");
	fs.writeFileSync(runnerPath, RUNNER_SCRIPT, { mode: 0o700 });
	fs.writeFileSync(path.join(resultDir, "command.txt"), input.command, { mode: 0o600 });
	fs.writeFileSync(path.join(resultDir, "cwd.txt"), path.resolve(input.cwd), { mode: 0o600 });
	fs.writeFileSync(
		path.join(resultDir, "artifacts.list"),
		`${input.requiredArtifacts.map(artifact => path.resolve(input.cwd, artifact)).join("\n")}\n`,
		{ mode: 0o600 },
	);
	return { runId, unit, resultDir, runnerPath };
}

/**
 * Start the job as a systemd user unit and return its durable identity.
 * Throws when the unit cannot be started; the caller must not hibernate then.
 */
export function launchJob(input: LaunchJobInput): LaunchedJob {
	if (!input.command.trim()) throw new Error("hibernation job command is empty");
	if (!fs.statSync(input.cwd).isDirectory()) throw new Error(`hibernation job cwd is not a directory: ${input.cwd}`);
	const availability = systemdUserAvailable();
	if (!availability.available) {
		throw new Error(`systemd --user is not available: ${availability.detail}`);
	}
	const { runId, unit, resultDir, runnerPath } = prepareJobDir(input);
	const commandSha = sha256Text(input.command);
	const env: Record<string, string> = {
		OMP_HIB_COMMAND_SHA: commandSha,
		OMP_HIB_RESULT_DIR: resultDir,
		OMP_HIB_JOB_ID: input.jobId,
		OMP_HIB_RUN_ID: runId,
		OMP_HIB_UNIT: unit,
		HOME: os.homedir(),
		PATH: process.env.PATH ?? "/usr/local/bin:/usr/bin:/bin",
		...(process.env.XDG_RUNTIME_DIR && { XDG_RUNTIME_DIR: process.env.XDG_RUNTIME_DIR }),
	};
	const argv = [
		"systemd-run",
		"--user",
		"--unit",
		unit,
		"--collect",
		"--property=KillMode=control-group",
		"--property=TimeoutStopSec=30",
		`--property=RuntimeMaxSec=${Math.max(1, Math.ceil(input.timeoutMs / 1000))}`,
		`--property=WorkingDirectory=${path.resolve(input.cwd)}`,
		...Object.entries(env).map(([key, value]) => `--setenv=${key}=${value}`),
		"/usr/bin/bash",
		runnerPath,
	];
	const result = runCommand(argv, { cwd: input.cwd, timeoutMs: 30_000 });
	if (result.exitCode !== 0) {
		throw new Error(`systemd-run failed (${result.exitCode}): ${(result.stderr || result.stdout).trim()}`);
	}
	const invocation = probeUnit(unit).invocationId;
	const startedAt = new Date().toISOString();
	const job: HibernationJob = {
		id: input.jobId,
		runId,
		command: input.command,
		commandSha256: commandSha,
		cwd: path.resolve(input.cwd),
		unit,
		...(invocation !== undefined && { invocationId: invocation }),
		resultDir,
		startedAt,
		timeoutMs: input.timeoutMs,
		requiredArtifacts: input.requiredArtifacts.map(artifact => path.resolve(input.cwd, artifact)),
		successExitCodes: input.successExitCodes ?? [0],
		launch: "systemd-user-transient",
	};
	return { job, ...(invocation !== undefined && { invocationId: invocation }) };
}

export interface UnitProbe {
	loadState: string;
	activeState: string;
	subState: string;
	result: string;
	exitCode?: number;
	invocationId?: string;
	active: boolean;
}

export function probeUnit(unit: string): UnitProbe {
	const result = runCommand([
		"systemctl",
		"--user",
		"show",
		unit,
		"--property=LoadState",
		"--property=ActiveState",
		"--property=SubState",
		"--property=Result",
		"--property=ExecMainStatus",
		"--property=InvocationID",
	]);
	const fields = new Map<string, string>();
	for (const line of result.stdout.split("\n")) {
		const index = line.indexOf("=");
		if (index > 0) fields.set(line.slice(0, index), line.slice(index + 1).trim());
	}
	const rawExit = Number.parseInt(fields.get("ExecMainStatus") ?? "", 10);
	const activeState = fields.get("ActiveState") ?? "unknown";
	return {
		loadState: fields.get("LoadState") ?? "unknown",
		activeState,
		subState: fields.get("SubState") ?? "unknown",
		result: fields.get("Result") ?? "unknown",
		...(Number.isSafeInteger(rawExit) && { exitCode: rawExit }),
		...(fields.get("InvocationID") && { invocationId: fields.get("InvocationID") }),
		active: activeState === "active" || activeState === "activating" || activeState === "reloading",
	};
}

export function stopUnit(unit: string): CommandResult {
	return runCommand(["systemctl", "--user", "stop", unit]);
}

/** Read the result contract, if the runner has published one. */
export function readJobResult(resultDir: string): JobResult | undefined {
	const file = path.join(resultDir, "result.json");
	try {
		return parseJobResult(JSON.parse(fs.readFileSync(file, "utf8")));
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
		throw error;
	}
}

export interface ArtifactCheck {
	ok: boolean;
	artifacts: ArtifactDigest[];
	missing: string[];
	incomplete: string[];
	digestMismatch: string[];
}

/**
 * Verify required artifacts exist, are non-empty, and still match the result
 * contract. A result whose artifacts failed verification never counts as a
 * successful completion.
 */
export function verifyArtifacts(job: HibernationJob, result: JobResult): ArtifactCheck {
	const byPath = new Map(result.artifacts.map(artifact => [path.resolve(artifact.path), artifact]));
	const missing: string[] = [];
	const incomplete: string[] = [];
	const digestMismatch: string[] = [];
	const verified: ArtifactDigest[] = [];
	for (const required of job.requiredArtifacts) {
		const absolute = path.resolve(required);
		let stat: fs.Stats;
		try {
			stat = fs.statSync(absolute);
		} catch {
			missing.push(absolute);
			continue;
		}
		if (!stat.isFile()) {
			missing.push(absolute);
			continue;
		}
		if (stat.size === 0) {
			incomplete.push(absolute);
			continue;
		}
		const recorded = byPath.get(absolute);
		if (!recorded) {
			incomplete.push(absolute);
			continue;
		}
		if (recorded.size !== stat.size) {
			digestMismatch.push(absolute);
			continue;
		}
		const actual = sha256File(absolute);
		if (actual !== recorded.sha256) {
			digestMismatch.push(absolute);
			continue;
		}
		verified.push(recorded);
	}
	return {
		ok: missing.length === 0 && incomplete.length === 0 && digestMismatch.length === 0,
		artifacts: verified,
		missing,
		incomplete,
		digestMismatch,
	};
}

export type ObservationKind =
	| { kind: "running"; detail: string }
	| { kind: "completed"; result: JobResult; artifacts: ArtifactCheck; detail: string }
	| { kind: "failed"; result?: JobResult; artifacts?: ArtifactCheck; detail: string }
	| { kind: "vanished"; detail: string };

/**
 * One observation of a job: running, completed (exit + artifacts verified),
 * failed, or vanished without a contract.
 */
export function observeJob(record: HibernationRecord): ObservationKind {
	const probe = probeUnit(record.job.unit);
	const result = readJobResult(record.job.resultDir);
	if (probe.active) {
		const elapsedMs = Date.now() - Date.parse(record.job.startedAt);
		return { kind: "running", detail: `${probe.activeState}/${probe.subState} for ${Math.round(elapsedMs / 1000)}s` };
	}
	if (result) {
		const artifacts = verifyArtifacts(record.job, result);
		if (record.job.successExitCodes.includes(result.exitCode) && artifacts.ok) {
			return {
				kind: "completed",
				result,
				artifacts,
				detail: `exit ${result.exitCode}; ${artifacts.artifacts.length} artifact(s) verified`,
			};
		}
		if (record.job.successExitCodes.includes(result.exitCode) && !artifacts.ok) {
			return {
				kind: "failed",
				result,
				artifacts,
				detail: `exit 0 but artifacts incomplete (${[...artifacts.missing, ...artifacts.incomplete, ...artifacts.digestMismatch].join(", ")})`,
			};
		}
		return { kind: "failed", result, artifacts, detail: `exit ${result.exitCode}` };
	}
	if (probe.loadState === "not-found" || probe.activeState === "inactive" || probe.activeState === "failed") {
		logger.warn("Hibernation job unit vanished without a result contract", {
			unit: record.job.unit,
			state: `${probe.activeState}/${probe.subState}/${probe.result}`,
		});
		return {
			kind: "vanished",
			detail: `unit ${probe.activeState}/${probe.subState}/${probe.result}; no result.json in ${record.job.resultDir}`,
		};
	}
	return { kind: "vanished", detail: `unit ${probe.activeState}/${probe.subState}; no result.json` };
}

export function tailFile(file: string, maxBytes = 8192): string {
	try {
		const stat = fs.statSync(file);
		const start = Math.max(0, stat.size - maxBytes);
		const fd = fs.openSync(file, "r");
		try {
			const buffer = Buffer.alloc(Math.min(stat.size, maxBytes));
			fs.readSync(fd, buffer, 0, buffer.length, start);
			return buffer.toString("utf8");
		} finally {
			fs.closeSync(fd);
		}
	} catch (error) {
		return `(unreadable: ${toError(error).message})`;
	}
}
